"""
paper_numbers.py  --  source of the paper numbers listed in README.md (section 5).

Note: section 1 of this script still applies the earlier threshold rule
(a median is reported only if at least half of the seeds cross) and reads the
historical Stream-AC/MountainCar files; Tables 3-5 of the manuscript are produced by
analysis/consolidated_final.py instead. Sections 2-5 are the ones used.

It reads only raw data (results/raw_final, raw_hardware, ablations) and does not
modify any data file. It writes:
    results/raw_summaries/paper_numbers.md
    results/raw_summaries/paper_numbers_tost.csv

Criteria (documented in the paper):
  * Final reward per seed: mean of the last 20 episodes (R20).
  * episodes_to_threshold: first episode at which the moving average of 20
    COMPLETE episodes (min_periods=20) reaches the threshold; the
    median across seeds is reported only if >= half of the seeds cross.
    (Previously min_periods=1: a single early episode could "cross".)
  * Seeds: lightweight agents 0-9 in the 3 environments; Standard DQN 0-4.
    Standard DQN uses the full-budget files:
      GridWorld  baseline_dqn_gridworld_{s}.csv   (300 ep)
      CartPole   baseline_dqn_cartpole_{s}_full.csv (1500 ep)
      MountainCar baseline_dqn_mountaincar_{s}_full.csv (2000 ep)
    and the extended probe baseline_dqn_gridworld_{s}_probe.csv.
  * Standard DQN FLOPs: recomputed analytically with 2 forwards
    (target + online) + 1 backward per sample (correction A1). The
    flops_per_update column of the raw CSVs keeps the old value (3 forwards).
  * Welch TOST, margin = 20% (and 10% sensitivity) of the Python mean.
    Equivalence: max(p_low, p_up) < 0.05. Non-inferiority (secondary,
    post hoc): p_low < 0.05  <=>  lower bound of the 90% CI > -margin.
  * Latency: per seed, mean over episodes of wall_time_s/steps; then
    mean +- SD across the 10 hardware seeds.
"""
import os
from itertools import combinations
import numpy as np
import pandas as pd
from scipy import stats

ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "results")
PY, HW, AB, OUT = (os.path.join(ROOT, d) for d in ("raw_final", "raw_hardware", "ablations", "raw_summaries"))
TH = {"gridworld": 1.5, "cartpole": 50.0, "mountaincar": -175.0}
LIGHT = ["stream_ac", "stream_q", "tiny_dqn"]
ENVS = ["gridworld", "cartpole", "mountaincar"]
DQN_FILE = {"gridworld": "baseline_dqn_gridworld_{s}.csv",
            "cartpole": "baseline_dqn_cartpole_{s}_full.csv",
            "mountaincar": "baseline_dqn_mountaincar_{s}_full.csv"}
DIMS = {"gridworld": (2, 4), "cartpole": (4, 2), "mountaincar": (2, 3)}
lines = []
def out(s=""):
    print(s); lines.append(s)

def load(path):
    return pd.read_csv(path).sort_values("episode").reset_index(drop=True)

def per_seed(files, env):
    finals, cross, steps = [], [], []
    for f in files:
        d = load(f); r = d["reward"]
        finals.append(r.values[-20:].mean())
        roll = r.rolling(20, min_periods=20).mean().values
        idx = np.where(roll >= TH[env])[0]
        if len(idx):
            cross.append(int(idx[0])); steps.append(int(d["steps"].values[: idx[0] + 1].sum()))
    n = len(files)
    ep = int(np.median(cross)) if len(cross) >= max(1, n // 2) else None
    st = int(np.median(steps)) if len(cross) >= max(1, n // 2) else None
    return np.array(finals), cross, ep, st

def dqn_flops(env):
    i, o = DIMS[env]; w = i * 64 + 64 * 64 + 64 * o
    return 32 * (2 * (2 * w) + 4 * w), 32 * (3 * (2 * w) + 4 * w)

# ---------------- 1. Python performance ----------------
out("# Paper figures (generated by analysis/paper_numbers.py)\n")
out("## 1. Python performance (R20 = mean of the last 20 ep)\n")
out("| env | agent | n | ep_thresh (median) | seeds crossing | steps to threshold (median) | R20 mean +- SD |")
out("|---|---|---|---|---|---|---|")
finals_py = {}
for env in ENVS:
    for a in LIGHT:
        fs = [f"{PY}/{a}_{env}_{s}.csv" for s in range(10)]
        f, c, ep, st = per_seed(fs, env); finals_py[(a, env)] = f
        out(f"| {env} | {a} | 10 | {ep if ep is not None else '---'} | {len(c)}/10 | {st if st else '---'} | {f.mean():.2f} +- {f.std(ddof=1):.2f} |")
    fs = [f"{PY}/" + DQN_FILE[env].format(s=s) for s in range(5)]
    f, c, ep, st = per_seed(fs, env)
    out(f"| {env} | standard_dqn | 5 | {ep if ep is not None else '---'} | {len(c)}/5 {c} | {st if st else '---'} | {f.mean():.2f} +- {f.std(ddof=1):.2f} |")
fs = [f"{PY}/baseline_dqn_gridworld_{s}_probe.csv" for s in range(5)]
f, c, ep, st = per_seed(fs, "gridworld")
out(f"\nDQN GridWorld probe: ep_thresh median {ep} (range {min(c)}-{max(c)}), steps median {st}, "
    f"final R20 {f.mean():.2f} +- {f.std(ddof=1):.2f}, episodes run {[len(load(x)) for x in fs]}")
mx = [load(f"{PY}/baseline_dqn_cartpole_{s}_full.csv")['reward'].rolling(20).mean().max() for s in range(5)]
out(f"DQN CartPole: maximum R20 per seed {np.round(mx, 1).tolist()}")
fs = [f"{PY}/baseline_dqn_cartpole_{s}_b.csv" for s in range(5)]
f, _, _, _ = per_seed(fs, "cartpole")
out(f"DQN CartPole at 300 ep (_b files, historical): R20 {f.mean():.2f} +- {f.std(ddof=1):.2f}")
pct = [(load(f"{PY}/stream_q_mountaincar_{s}.csv")['reward'] > -200).mean() * 100 for s in range(10)]
out(f"Stream-Q MountainCar: % of episodes with return > -200: mean {np.mean(pct):.1f} (range {min(pct):.1f}-{max(pct):.1f})")

# ---------------- 2. Tests between agents ----------------
out("\n## 2. Kruskal-Wallis + Mann-Whitney (Holm)\n")
for env in ["gridworld", "cartpole"]:
    g = {a: finals_py[(a, env)] for a in LIGHT}
    H, p = stats.kruskal(*g.values())
    out(f"{env}: H={H:.2f}, p={p:.4f}")
    ps = sorted([(a, b, stats.mannwhitneyu(g[a], g[b], alternative='two-sided').pvalue) for a, b in combinations(LIGHT, 2)], key=lambda x: x[2])
    for i, (a, b, pp) in enumerate(ps):
        out(f"   {a} vs {b}: p={pp:.4f}, Holm-adj={min(1, pp * (3 - i)):.4f}")

# ---------------- 3. Resources ----------------
out("\n## 3. Persistent state and FLOPs/update\n")
out("| env | agent | memory (B) | FLOPs/update | note |")
out("|---|---|---|---|---|")
sac = {}
for env in ENVS:
    for a in LIGHT:
        d = load(f"{PY}/{a}_{env}_0.csv")
        out(f"| {env} | {a} | {int(d.memory_bytes[0])} | {int(d.flops_per_update[0])} | |")
        if a == "stream_ac": sac[env] = (int(d.memory_bytes[0]), int(d.flops_per_update[0]))
    d = load(f"{PY}/" + DQN_FILE[env].format(s=0)); new, old = dqn_flops(env)
    assert old == int(d.flops_per_update[0]), "old count does not match the CSV"
    out(f"| {env} | standard_dqn | {int(d.memory_bytes[0])} | {new} | raw CSV: {old} (3 forwards) |")
    sac[env] += (int(d.memory_bytes[0]), new)
mr = [v[2] / v[0] for v in sac.values()]; fr = [v[3] / v[1] for v in sac.values()]
out(f"\nStream-AC vs DQN: memory {min(mr):.0f}-{max(mr):.0f}x; FLOPs {min(fr):.0f}-{max(fr):.0f}x  {[(e, round(v[3]/v[1])) for e, v in sac.items()]}")

# ---------------- 4. Hardware: TOST and latency ----------------
out("\n## 4. Hardware vs Python (10 + 10 seeds)\n")
out("| agent | env | HW R20 | Py R20 | Delta | margin | p_TOST | p_low | CI90 | class | MW p |")
out("|---|---|---|---|---|---|---|---|---|---|---|")
rows = []
for env in ["gridworld", "cartpole"]:
    for a in LIGHT:
        hw = np.array([load(f"{HW}/{a}_{env}_esp32_seed{s}.csv")['reward'].values[-20:].mean() for s in range(10)])
        py = finals_py[(a, env)]
        mw = stats.mannwhitneyu(hw, py, alternative="two-sided").pvalue
        d = hw.mean() - py.mean(); va, vb = hw.var(ddof=1) / 10, py.var(ddof=1) / 10; se = np.sqrt(va + vb)
        dfw = (va + vb) ** 2 / (va ** 2 / 9 + vb ** 2 / 9); tc = stats.t.ppf(0.95, dfw)
        for m in (0.20, 0.10):
            eps = m * abs(py.mean())
            pl = stats.t.sf((d + eps) / se, dfw); pu = stats.t.cdf((d - eps) / se, dfw)
            cls = "Eq" if max(pl, pu) < 0.05 else ("NI" if pl < 0.05 else "Inc")
            rows.append(dict(agent=a, env=env, margin=m, hw=hw.mean(), hw_sd=hw.std(ddof=1), py=py.mean(), py_sd=py.std(ddof=1),
                             delta=d, eps=eps, p_tost=max(pl, pu), p_low=pl, p_up=pu, ci_lo=d - tc * se, ci_hi=d + tc * se, cls=cls, mw_p=mw))
            out(f"| {a} | {env} | {hw.mean():.2f}+-{hw.std(ddof=1):.2f} | {py.mean():.2f}+-{py.std(ddof=1):.2f} | {d:+.2f} | {int(m*100)}% | {max(pl,pu):.3f} | {pl:.4f} | [{d-tc*se:+.2f},{d+tc*se:+.2f}] | {cls} | {mw:.3f} |")
pd.DataFrame(rows).to_csv(f"{OUT}/paper_numbers_tost.csv", index=False)
out("\nLatencia (us/step):")
for env in ["gridworld", "cartpole"]:
    for a in LIGHT:
        m = [(load(f"{HW}/{a}_{env}_esp32_seed{s}.csv").eval("wall_time_s/steps").mean() * 1e6) for s in range(10)]
        out(f"   {a} {env}: {np.mean(m):.2f} +- {np.std(m, ddof=1):.2f}")

# ---------------- 5. Ablations ----------------
out("\n## 5. Ablations (all tested values)\n")
for f in ["ablation_bins.csv", "ablation_lambda.csv", "ablation_buffer.csv", "ablation_entropy.csv"]:
    d = pd.read_csv(f"{AB}/{f}")
    g = d.groupby(["env", "param_value"]).agg(n=("seed", "nunique"), R=("tail_mean", "mean"), sd=("tail_mean", "std"),
                                               mem=("memory_bytes", "first"), flops=("flops_per_update", "first"))
    out(f"### {f}\n```\n{g.round(2).to_string()}\n```")

with open(f"{OUT}/paper_numbers.md", "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines) + "\n")
