<#
run_x1_x2.ps1 -- Runs the full grid of ONE ablation (X1 or X2) with
the original .venv. It does NOT include X3 (MountainCar): that parameter does not exist in
this script.

X1 : Stream-Q/CartPole, uniform discretizations u6,u9,u12,u18,u24
     (10 seeds, 1500 episodes each). Requires a valid controls/C1_PASSED.json.
     It reuses the 'ref' [6,6,12,12] reference already generated by C1;
     it does not re-run it.
X2 : Stream-AC/CartPole, beta_e = 0.00, 0.01, 0.10, 0.30 (10 seeds, 1500
     episodes each). Requires a valid controls/C2_PASSED.json. It reuses the
     ref_b005 reference (beta_e=0.05) already generated by C2; it does not re-run it.

Usage (from any folder):
  powershell -NoProfile -ExecutionPolicy Bypass -File <repository>\research\experiments\run_x1_x2.ps1 -Ablation X1
  powershell -NoProfile -ExecutionPolicy Bypass -File <repository>\research\experiments\run_x1_x2.ps1 -Ablation X2
  Add -DryRun to check configuration, memory and FLOPs without running episodes.
#>
param(
    [Parameter(Mandatory = $true)][ValidateSet('X1', 'X2')][string]$Ablation,
    [switch]$DryRun
)
$ErrorActionPreference = 'Stop'
$Research = Split-Path -Parent $PSScriptRoot
$Py = Join-Path $Research '.venv\Scripts\python.exe'
if (-not (Test-Path $Py)) { throw ".venv Python not found: $Py" }
$ver = (& $Py -c "import sys; print(sys.version.split()[0])").Trim()
if ($ver -ne '3.10.0') { throw "Unexpected .venv version: $ver (expected 3.10.0)" }
$np = (& $Py -c "import numpy, gymnasium; print(numpy.__version__ + ' ' + gymnasium.__version__)").Trim()
if ($np -ne '2.2.6 0.29.1') { throw "Unexpected numpy/gymnasium in the .venv: $np (expected '2.2.6 0.29.1')" }

$env:PYTHONIOENCODING = 'utf-8'
$env:PYTHONDONTWRITEBYTECODE = '1'
$cmdLine = "run_x1_x2.ps1 -Ablation $Ablation" + $(if ($DryRun) { ' -DryRun' } else { '' })
$env:CONTROL_COMMAND = $cmdLine

switch ($Ablation) {
    'X1' { $pyArgs = @('-W', 'ignore', (Join-Path $PSScriptRoot 'run_ablations_cartpole.py'), '--stage', 'grid') }
    'X2' { $pyArgs = @('-W', 'ignore', (Join-Path $PSScriptRoot 'run_ablations_streamac_beta.py'), '--stage', 'grid') }
}
if ($DryRun) { $pyArgs += '--dry-run' }

$LogDir = Join-Path $Research 'results\derived\controls\logs'
New-Item -ItemType Directory -Force -Path $LogDir | Out-Null
$stamp = (Get-Date).ToUniversalTime().ToString('yyyyMMddTHHmmssZ')
$Log = Join-Path $LogDir ("{0}{1}_{2}.log" -f $Ablation, $(if ($DryRun) { '_dryrun' } else { '' }), $stamp)
if (Test-Path $Log) { throw "The log already exists: $Log" }
"# $cmdLine | start UTC $stamp | python $ver | numpy/gymnasium $np" | Out-File -FilePath $Log -Encoding utf8

Write-Host "Running $cmdLine  (log: $Log)"
$ErrorActionPreference = 'Continue'
& $Py @pyArgs 2>&1 | ForEach-Object { $line = "$_"; Write-Host $line; Add-Content -Path $Log -Value $line -Encoding utf8 }
$code = $LASTEXITCODE
"# end UTC $((Get-Date).ToUniversalTime().ToString('yyyyMMddTHHmmssZ')) | exit code $code" | Add-Content -Path $Log -Encoding utf8
Write-Host "Ablation $Ablation finished with code $code"
exit $code
