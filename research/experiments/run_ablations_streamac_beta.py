"""
run_ablations_streamac_beta.py -- Protocol X2: ablation of the entropy
coefficient (beta_e) of Linear Stream-AC in CartPole (1500 episodes, seeds 0-9).

Standalone script: it does NOT modify run_single.py. It calls
run_single.run() directly with params_override (the same path already used by control C2
in run_controls.py), changing only entropy_coef. alpha_actor,
alpha_critic and gamma stay fixed at the values already validated by C2.

The beta_e = 0.05 configuration (control C2) ALREADY EXISTS in
results/derived/ablations_cartpole_1500/stream_ac_beta/ref_b005/ and is NOT
re-run here: this script only runs the 4 new authorized
configurations (b000=0.00, b001=0.01, b010=0.10, b030=0.30). Before running,
it checks that C2_PASSED.json is valid (code/config hashes unchanged
since ref_b005 was generated) and that ref_b005/ exists with its 10 CSVs intact.

Stages:
  --stage grid : runs b000, b001, b010, b030 (10 seeds each). Requires
                 a valid controls/C2_PASSED.json; refuses to run if
                 any code/config hash changed since C2, or if ref_b005/
                 does not have its 10 CSVs.
  --dry-run    : shows the resolved configuration and checks that
                 memory_bytes/flops_per_update are invariant with respect to
                 beta_e (the structure of StreamACAgent does not depend on
                 entropy_coef), without running any episode or creating anything.

Outputs (never in raw_*/ or ablations/; never overwrites; never touches
ref_b005/):
  results/derived/ablations_cartpole_1500/stream_ac_beta/<config>/stream_ac_cartpole_{seed}.csv
  results/derived/ablations_cartpole_1500/stream_ac_beta/<config>/run_meta.json
CSV schema identical to raw_final (core.metrics.EpisodeLogger), like ref_b005.
"""
import argparse
import hashlib
import json
import os
import sys
import time

import numpy as np
import yaml

RESEARCH = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, RESEARCH)

import gymnasium as gym

from experiments.run_single import run, make_agent, CONFIG_PATH
from experiments import controls_common as cc

AGENT, ENV = "stream_ac", "cartpole"
RESULTS = os.path.join(RESEARCH, "results")
OUT_ROOT = os.path.join(RESULTS, "derived", "ablations_cartpole_1500", "stream_ac_beta")
REF_DIR = os.path.join(OUT_ROOT, "ref_b005")          # already generated by control C2; NEVER rewritten here
OFFICIAL_C2 = os.path.join(RESULTS, "derived", "controls", "C2_streamac_beta_ref")
SEEDS = list(range(10))
EXPECTED_EPISODES = 1500

# alpha_actor/alpha_critic/gamma: the same values already validated by control C2.
BASE_PARAMS = {"alpha_actor": 0.005, "alpha_critic": 0.01, "gamma": 0.99}
BETAS = {"b000": 0.00, "b001": 0.01, "b010": 0.10, "b030": 0.30}


def params_for(config_id):
    return dict(BASE_PARAMS, entropy_coef=BETAS[config_id])


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def provenance():
    return {"utc": cc.now(), "argv": sys.argv, "command": os.environ.get("CONTROL_COMMAND", " ".join(sys.argv)),
            "environment": cc.environment(), "code_sha256": cc.code_hashes()}


def guard_out(path):
    rp = os.path.realpath(path)
    if "derived" not in rp:
        raise SystemExit(f"The output must be inside results/derived: {rp}")
    if rp == os.path.realpath(REF_DIR):
        raise SystemExit("Writing over ref_b005 is forbidden (generated by control C2, not re-run in X2).")


def check_ref_b005_intact():
    """Checks that ref_b005/ (beta_e=0.05, control C2) exists with its 10 CSVs and
    that their hashes match those recorded in C2_streamac_beta_ref/results.json.
    It re-runs nothing; it only reads. The status string below is compared verbatim
    with the (Spanish) status stored in that results.json, so it is not translated."""
    res_path = os.path.join(OFFICIAL_C2, "results.json")
    if not os.path.exists(res_path):
        raise SystemExit(f"The result of control C2 does not exist: {res_path}")
    res = json.load(open(res_path, encoding="utf-8"))
    if res["status"] != "C2 SUPERADO (10/10 seeds idénticas)":
        raise SystemExit(f"C2 has not passed: {res['status']}")
    for r in res["rows"]:
        fn = f"{AGENT}_{ENV}_{r['seed']}.csv"
        path = os.path.join(REF_DIR, fn)
        if not os.path.exists(path):
            raise SystemExit(f"Missing ref_b005 reference CSV: {path}")
        cur = sha256(path)
        if cur != r["sha256_new"]:
            raise SystemExit(f"ref_b005/{fn} changed since C2 generated it (different hash). Stopping.")
    return res["params_override"]


def expected_cost(params):
    """memory_bytes/flops_per_update of StreamACAgent in CartPole (n_features=4,
    n_actions=2): they do not depend on alpha_actor/alpha_critic/gamma/entropy_coef,
    only on n_features and n_actions. They must be identical for every beta_e."""
    env = gym.make("CartPole-v1")
    agent = make_agent(AGENT, ENV, env, None, {"agents": {AGENT: params}}, np.random.default_rng(0),
                        params_override=params)
    return agent.memory_bytes(), agent.flops_per_update()


def run_config(config_id, seeds, episodes, cfg, params):
    out_dir = os.path.join(OUT_ROOT, config_id)
    guard_out(out_dir)
    targets = [os.path.join(out_dir, f"{AGENT}_{ENV}_{s}.csv") for s in seeds]
    for p in targets:
        cc.assert_new_output(p)
    os.makedirs(out_dir, exist_ok=True)
    meta = {"protocol": "X2", "config_id": config_id, "entropy_coef": BETAS[config_id],
            "params": params, "episodes": episodes, "seeds": seeds,
            "reset_seed": "seed + episode", "rng": "numpy.random.default_rng(seed)",
            "provenance_start": provenance()}
    t0 = time.time()
    for s, path in zip(seeds, targets):
        rows = run(AGENT, ENV, s, episodes, cfg, params_override=params, out_dir=out_dir)
        print(f"[{config_id}] seed {s}: {len(rows)} ep, R20={np.mean([r['reward'] for r in rows[-20:]]):.2f} "
              f"({time.time() - t0:.0f}s)", flush=True)
    meta["wall_clock_s"] = round(time.time() - t0, 1)
    meta["outputs_sha256"] = {os.path.basename(p): sha256(p) for p in targets}
    with open(os.path.join(out_dir, "run_meta.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2, ensure_ascii=False)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", choices=["grid"], required=True)
    ap.add_argument("--configs", nargs="+", default=None, help="default: b000 b001 b010 b030")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    with open(CONFIG_PATH) as f:
        cfg = yaml.safe_load(f)
    episodes = cfg["envs"][ENV]["episodes"]
    assert episodes == EXPECTED_EPISODES, f"protocol X2 requires {EXPECTED_EPISODES} episodes (config.yaml has {episodes})"

    configs = args.configs or list(BETAS.keys())
    bad = [c for c in configs if c not in BETAS]
    if bad:
        raise SystemExit(f"unknown configuration (only b000,b001,b010,b030): {bad}")

    costs = set()
    for c in configs:
        params = params_for(c)
        mem, fl = expected_cost(params)
        costs.add((mem, fl))
        print(f"{c:5s} entropy_coef={BETAS[c]:.2f} params={params} memory_bytes={mem} flops_per_update={fl}")
    assert len(costs) == 1, f"memory/flops should not depend on beta_e, but they vary: {costs}"
    print(f"episodes={episodes} seeds={SEEDS} reset=seed+episode (invariant memory/flops: {costs.pop()})")

    if args.dry_run:
        return

    ok, why = cc.check_passed("C2")
    if not ok:
        raise SystemExit(f"Gate closed (C2): {why}")
    ref_params = check_ref_b005_intact()
    print(f"ref_b005 (beta_e=0.05, control C2) intacto. params_override registrado: {ref_params}")

    for c in configs:
        run_config(c, SEEDS, episodes, cfg, params_for(c))


if __name__ == "__main__":
    main()
